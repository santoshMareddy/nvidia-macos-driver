#!/bin/bash
# Recompile kernel.comp to SPIR-V and rewrite kernel_spv.h (needs glslangValidator and python3; spirv-val if present).
#   tools/nvk-compute-check/regen-spirv.sh            rewrite the header
#   tools/nvk-compute-check/regen-spirv.sh --check    only compile and validate; leave the header alone
set -euo pipefail
D=$(cd "$(dirname "$0")" && pwd); T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
glslangValidator -V --target-env vulkan1.2 -o "$T/kernel.spv" "$D/kernel.comp" > "$T/glslang.log" || { cat "$T/glslang.log"; exit 1; }
if command -v spirv-val >/dev/null 2>&1; then spirv-val --target-env vulkan1.2 "$T/kernel.spv"; fi
[ "${1:-}" = --check ] && { echo "kernel.comp compiles and validates ($(stat -c %s "$T/kernel.spv" 2>/dev/null || stat -f %z "$T/kernel.spv") bytes)"; exit 0; }
python3 - "$T/kernel.spv" "$D/kernel_spv.h" <<'PY'
import struct, sys
words = struct.unpack("<%dI" % (len(open(sys.argv[1], "rb").read()) // 4), open(sys.argv[1], "rb").read())
with open(sys.argv[2], "w") as out:
    out.write("/* Generated by regen-spirv.sh from kernel.comp (glslangValidator -V --target-env vulkan1.2). Do not edit. */\n")
    out.write("#include <stdint.h>\n#include <stddef.h>\nstatic const uint32_t kernel_spv[] = {\n")
    for i in range(0, len(words), 8):
        out.write("    " + ", ".join("0x%08x" % w for w in words[i:i+8]) + ",\n")
    out.write("};\nstatic const size_t kernel_spv_bytes = sizeof kernel_spv;\n")
print("wrote", sys.argv[2], len(words), "words")
PY
